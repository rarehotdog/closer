/**
 * Platforms whose prices are recorded in the given currency (KR platforms in KRW, global
 * platforms in USD). Price entry forms list only these, so a number typed in one currency
 * is never filed under a platform that quotes another currency.
 */
export function platformsForCurrency(
  currency: CurrencyCode,
): ResalePlatformInfo[] {
  const region = currency === 'KRW' ? 'KR' : 'GLOBAL';
  return RESALE_PLATFORMS.filter((p) => p.region === region);
}

